package pl.cloud.crudmig;

public class CompetitorDTO {
    private String name;
    private String surname;
    private String clubName;

    public CompetitorDTO() {
    }

    public String getName() {
        return name;
    }

    public String getSurname() {
        return surname;
    }

    public String getClubName() {
        return clubName;
    }
}
